const COLUMN: Record<Locale, 0 | 1 | 2> = { tr: 0, en: 1, ru: 2 };

/** Ülke sayfası slug'ı istenen dilde: `DE` + en → `de-germany`. Tanınmayan kod → null. */
export function localizedCountrySlug(code: string, locale: Locale): string | null {
  const cc = code.toUpperCase();
  const row = NAMES[cc];
  return row ? `${cc.toLowerCase()}-${row[COLUMN[locale]]}` : null;
}

/**
 * `[ulke]` parçasını hedef dile çevirir: kod önekten okunur (`de-…` → DE),
 * ad kısmı ne olursa olsun (eski Türkçe ad, başka dil) o dilin biçimine
 * yazılır. Kod tanınmıyorsa parça olduğu gibi kalır (sayfa 404'ünü kendisi verir).
 */
export function localizeCountrySlugParam(slug: string, locale: Locale): string {
  const m = /^([a-z]{2})(?:-|$)/i.exec(slug);
  return (m && localizedCountrySlug(m[1]!, locale)) ?? slug;
}

